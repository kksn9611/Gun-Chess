/// <summary>
/// Stat types that synergy buffs can modify.
/// Used by SynergyBehavior (StatBoostBehavior).
/// </summary>
public enum StatType
{
    Att,        // Attack power (%)
    Def,        // Defense (%)
    AttSpd,     // Attack speed (%)
    MaxHp,      // Max HP (%)
    MoveSpd,    // Move speed (%)
    MpGain,     // MP gain (%)
    SkillDmg    // Skill damage multiplier (%)
}
